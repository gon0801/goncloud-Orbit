sql = (
    "SELECT DISTINCT ON(metric_date) metric_date,observed_at FROM ads_"
    "metric_observation WHERE ad_entity_id=%s AND metric_date BETWEEN "
    "%s AND %s AND observed_at<=%s ORDER BY metric_date,observed_at DE"
    "SC"
)
dsn = os.environ["ORBIT_DSN_READ"]
register_secret(dsn)
try:
    with connect(dsn) as c:
        c.execute("SET TRANSACTION READ ONLY")
        c.execute("SET LOCAL statement_timeout='15s'")
        now = c.execute("SELECT now()").fetchone()[0]
        out = []
        for row in COHORT:
            asof = dt.datetime.fromisoformat(row["as_of"])
            horizon = asof + dt.timedelta(days=10)
            r = {
                **row,
                "horizon": horizon,
                "status": "horizonte_futuro" if horizon > now else "medida",
            }
            if horizon <= now:
                args = (row["entity"], row["desde"], row["hasta"])
                old = dict(c.execute(sql, (*args, asof)))
                new = dict(c.execute(sql, (*args, horizon)))
                revised = [d for d, t in new.items() if t > asof]
                r.update(
                    {
                        "dates_asof": len(old),
                        "dates_10d": len(new),
                        "same_dates": old.keys() == new.keys(),
                        "revised_dates": len(revised),
                        "all_dates_revised": bool(old)
                        and old.keys() == new.keys()
                        and len(revised) == len(old),
                        "observations_10d": new,
                    }
                )
                r["observations_10d"] = {str(k): v for k, v in new.items()}
            out.append(r)
    print(json.dumps({"utc": now, "sql": sql, "cohorts": out}, default=str))
except Exception as e:
    print(json.dumps({"error": scrub(str(e))}))
    raise SystemExit(1) from None
